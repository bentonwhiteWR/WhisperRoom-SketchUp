  def self.run_ui
    keys = %w[shots dry out over check recover]
    prompts = ['Shots — pilot / all / CU-03,CU-06:seated',
               'Dry run — resolve names and cameras only',
               'Output folder',
               'Overwrite files already there',
               'Anchor check images (red dots)',
               'Recover brightness after export']
    defaults = { 'shots' => 'pilot', 'dry' => 'Yes', 'out' => DEF_OUT, 'over' => 'No',
                 'check' => 'Yes', 'recover' => 'Yes' }
    vals = keys.map do |k|
      v = Sketchup.read_default(PREF, k, defaults[k]).to_s
      v.empty? ? defaults[k] : v
    end
    lists = ['', 'Yes|No', '', 'No|Yes', 'Yes|No', 'Yes|No']
    res = UI.inputbox(prompts, vals, lists, 'Assembly close-ups')
    return unless res
    cfg = {}
    keys.each_with_index { |k, i| cfg[k] = res[i].to_s.strip }
    keys.each { |k| Sketchup.write_default(PREF, k, cfg[k]) }
    s = run('shots' => cfg['shots'], 'dry' => cfg['dry'] == 'Yes', 'out' => cfg['out'],
            'over' => cfg['over'] == 'Yes', 'check' => cfg['check'] == 'Yes',
            'recover' => cfg['recover'] == 'Yes')
    lines = s['shots'].map { |r| "#{r['shot']} #{r['variant']}: #{r['status']}" }
    UI.messagebox("Assembly close-ups (#{s['mode']})\n\n#{lines.join("\n")}\n\n" \
                  "#{s['restored'] ? 'Model restored exactly.' : 'MODEL NOT IDENTICAL — see the diagnostics.'}\n" \
                  "#{s['diagnostics']}")
  rescue StandardError => e
    UI.messagebox("Assembly close-ups failed:\n\n#{e.class}: #{e.message}")
    puts "FAILED: #{e.class}: #{e.message}"
    puts e.backtrace.first(5)
  end
