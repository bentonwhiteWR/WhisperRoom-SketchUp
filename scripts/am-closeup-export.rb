  def self.arr(p)
    [p.x.to_f, p.y.to_f, p.z.to_f]
  end

  def self.p3(a)
    Geom::Point3d.new(a[0].to_f, a[1].to_f, a[2].to_f)
  end

  def self.v3(a)
    Geom::Vector3d.new(a[0].to_f, a[1].to_f, a[2].to_f)
  end

  def self.ident
    Geom::Transformation.new
  end

  def self.axis_vec(ax)
    return v3(ax) if ax.is_a?(Array)
    { 'x' => X_AXIS, 'y' => Y_AXIS, 'z' => Z_AXIS }[ax.to_s.downcase] || Z_AXIS
  end

  def self.ent_name(e)
    if e.is_a?(Sketchup::ComponentInstance)
      (e.definition.name.to_s rescue '')
    elsif e.is_a?(Sketchup::Group)
      n = (e.name.to_s rescue '')
      n.empty? ? ((e.definition.name.to_s rescue '')) : n
    else
      e.class.name.split('::').last
    end
  end

  def self.inst?(e)
    e.is_a?(Sketchup::ComponentInstance) || e.is_a?(Sketchup::Group)
  end

  def self.sub_ents(e)
    return e.entities if e.is_a?(Sketchup::Group)
    return e.definition.entities if e.is_a?(Sketchup::ComponentInstance)
    nil
  end

  def self.defn_of(e)
    return e.definition if e.is_a?(Sketchup::ComponentInstance)
    return (e.definition rescue e.entities.parent) if e.is_a?(Sketchup::Group)
    nil
  end

  # Box of a definition's raw bounds carried through a transformation.
  def self.raw_box(e, tr)
    d = defn_of(e)
    b = d ? d.bounds : (e.bounds rescue nil)
    return nil if b.nil? || !b.valid?
    pts = (0..7).map { |i| arr(b.corner(i).transform(d ? tr * e.transformation : tr)) }
    box_union(pts.map { |p| [p, p] })
  end

  # Visible-geometry box: faces only, hidden entities and off tags skipped —
  # the angled rig's rule, because a swing arc or a hidden helper inside a
  # part would otherwise move an anchor by inches. Falls back to raw bounds.
  def self.vis_walk(ents, tr, acc, st, depth)
    ents.each do |e|
      break if st[:n] >= WALK_MAX_NODES
      st[:n] += 1
      next if (e.hidden? rescue false)
      l = (e.layer rescue nil)
      next if l && !(l.visible? rescue true)
      if e.is_a?(Sketchup::Face)
        e.vertices.each { |v| acc << arr(v.position.transform(tr)) }
        st[:faces] += 1
      elsif inst?(e) && depth < WALK_MAX_DEPTH
        sub = sub_ents(e)
        vis_walk(sub, tr * e.transformation, acc, st, depth + 1) if sub
      end
    end
  end

  def self.vis_box(e, ptr)
    if inst?(e)
      acc = []
      st = { :n => 0, :faces => 0 }
      vis_walk(sub_ents(e), ptr * e.transformation, acc, st, 0)
      return box_union(acc.map { |p| [p, p] }) unless acc.empty?
      return raw_box(e, ptr)
    end
    b = (e.bounds rescue nil)
    return nil if b.nil? || !b.valid?
    box_union([[arr(b.min.transform(ptr)), arr(b.min.transform(ptr))],
               [arr(b.max.transform(ptr)), arr(b.max.transform(ptr))]])
  end

  # Every component instance and group in the model, nested ones included,
  # with its WORLD transformation and the names of its ancestors. The staging
  # group is skipped. Built once per run: shots are aborted, so the model the
  # index describes does not change between them.
  def self.instance_index(model, skip, ents = nil)
    out = []
    st = { :n => 0 }
    # :mat is the material the instance RENDERS with: its own, else the
    # nearest painted ancestor's (SketchUp paints default faces that way).
    # A re-instanced copy has to carry it, or a painted wall comes out white.
    walk = lambda do |ents, tr, path, depth, pmat|
      ents.each do |e|
        break if st[:n] >= WALK_MAX_NODES
        next unless inst?(e)
        next if skip && e == skip
        st[:n] += 1
        wtr = tr * e.transformation
        nm = ent_name(e)
        mat = (e.material rescue nil) || pmat
        out << { :ent => e, :tr => wtr, :ptr => tr, :name => nm, :path => path, :mat => mat }
        walk.call(sub_ents(e), wtr, path + [nm], depth + 1, mat) if depth < WALK_MAX_DEPTH
      end
    end
    walk.call(ents || model.entities, ident, [], 0, nil)
    [out, st[:n] >= WALK_MAX_NODES]
  end

  # --------------------------------------------------------- the fingerprint --

  def self.cam_sig(c)
    s = [arr(c.eye).map { |v| r3(v) }, arr(c.target).map { |v| r3(v) },
         arr(c.up).map { |v| r3(v) }, c.perspective?]
    s << (c.perspective? ? r3(c.fov) : r3((c.height rescue 0)))
    s << r3((c.aspect_ratio rescue 0))
    s
  end

  def self.fingerprint(model)
    ents = model.entities
    ro = model.rendering_options
    si = model.shadow_info
    keys = WR_Shading::TRANSPARENCY.keys + SECTION_RO.keys
    {
      'title'          => model.title.to_s,
      'path'           => model.path.to_s,
      'entities'       => ents.length,
      'hidden_top'     => ents.count { |e| (e.hidden? rescue false) },
      'definitions'    => model.definitions.length,
      'materials'      => model.materials.length,
      'layers_visible' => model.layers.map { |l| "#{l.name}=#{(l.visible? rescue '?')}" }.join('|'),
      'pages'          => model.pages.count,
      'selected_page'  => (model.pages.selected_page ? model.pages.selected_page.name : ''),
      'style'          => (model.styles.selected_style.name rescue ''),
      'active_section' => ((ents.active_section_plane ? 'set' : 'none') rescue 'n/a'),
      'active_path'    => (model.active_path ? model.active_path.length : 0),
      'rendering'      => keys.map { |k| "#{k}=#{(ro[k] rescue 'n/a')}" }.join('|'),
      'shadow'         => WR_Shading::SHADOW_KEYS.map { |k| "#{k}=#{(si[k] rescue 'n/a')}" }.join('|'),
      'camera'         => cam_sig(model.active_view.camera).inspect,
      'modified'       => (model.modified? rescue 'n/a')
    }
  end

  def self.fp_diff(a, b)
    a.keys.reject { |k| a[k] == b[k] }.map { |k| "#{k}: #{a[k]} -> #{b[k]}" }
  end

  # -------------------------------------------------------- style + camera --

  def self.push_section_ro(model)
    ro = model.rendering_options
    saved = {}
    stuck = []
    SECTION_RO.each do |k, v|
      saved[k] = (ro[k] rescue nil)
      next if saved[k].nil?   # key not in this SketchUp: nothing to set or restore
      begin
        ro[k] = v
      rescue StandardError => e
        stuck << "#{k}: write raised #{e.class}"
        next
      end
      got = (ro[k] rescue :unreadable)
      stuck << "#{k}: wanted #{v.inspect}, still #{got.inspect}" unless got == v
    end
    [saved, stuck]
  end

  def self.pop_section_ro(model, saved)
    ro = model.rendering_options
    (saved || {}).each { |k, v| (ro[k] = v) rescue nil unless v.nil? }
  end

  def self.save_camera(view)
    c = view.camera
    { :eye => c.eye, :target => c.target, :up => c.up, :persp => c.perspective?,
      :fov => (c.fov rescue nil), :height => (c.height rescue nil),
      :aspect => (c.aspect_ratio rescue 0.0) }
  end

  def self.restore_camera(view, s)
    return if s.nil?
    c = view.camera
    # Projection FIRST: switching parallel -> perspective after set() lets
    # SketchUp re-derive the eye distance, and the restored camera drifted.
    c.perspective = s[:persp]
    c.set(s[:eye], s[:target], s[:up])
    (c.aspect_ratio = s[:aspect].to_f) rescue nil
    if s[:persp]
      (c.fov = s[:fov]) rescue nil if s[:fov]
    else
      (c.height = s[:height]) rescue nil if s[:height]
    end
    view.refresh rescue nil
  end

  def self.close_contexts(model)
    n = 0
    while model.active_path && n < 20
      break unless model.close_active
      n += 1
    end
    n
  rescue StandardError
    n
  end

