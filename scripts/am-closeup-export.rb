  # Definitions a shot loaded that outlived its abort: removed again, newest
  # first, only if nothing uses them and they were not in the model before.
  def self.cleanup_defs(model, before_ids)
    gone = []
    # One pass per nesting level: a child only loses its last instance when
    # its parent goes. Assembled booths nest ten and more deep.
    40.times do
      extra = model.definitions.to_a.reject { |d| before_ids.include?(d.persistent_id) }
      extra = extra.select { |d| d.instances.empty? }
      break if extra.empty?
      model.start_operation('WR close-up cleanup', true)
      extra.each do |d|
        nm = d.name
        gone << nm if (model.definitions.remove(d) rescue false)
      end
      model.commit_operation
    end
    gone
  rescue StandardError => e
    ["cleanup failed: #{e.class}: #{e.message}"]
  end

  # Every in_file a picked shot names, loaded once before the shots and
  # OUTSIDE every operation (an aborted load would take the definition with
  # it). They place no instance, so cleanup_defs removes them at the end.
  def self.preload_files(run, poses, jobs)
    want = []
    scan = lambda do |o|
      case o
      when Hash
        want << o['in_file'].to_s if o['in_file']
        o.each { |k, v| scan.call(v) unless k.to_s.start_with?('_') }
      when Array then o.each { |v| scan.call(v) }
      end
    end
    jobs.each do |sid, var|
      pz = poses[sid] || {}
      scan.call(merge_pose(pz['base'], (pz['variants'] || {})[var]))
    end
    want.uniq.each do |f|
      path = f
      unless path =~ /\A[A-Za-z]:[\\\/]/
        path = run[:roots].map { |r| File.join(r, f) }.find { |c| File.exist?(c) } || f
      end
      d = File.exist?(path) ? (run[:model].definitions.load(path) rescue nil) : nil
      run[:infile][f] = d if d
      puts "  preload #{f}: #{d ? d.name : 'FAILED'}"
    end
  end

  # Materials a file load brought in that outlived the aborts: removed again
  # when nothing in the model uses them and they were not there before.
  def self.cleanup_materials(model, before_names)
    extra = model.materials.to_a.reject { |m| before_names.include?(m.name) }
    return [] if extra.empty?
    used = {}
    model.definitions.each do |d|
      d.entities.each do |e|
        used[e.material] = true if e.respond_to?(:material) && e.material
        used[e.back_material] = true if e.is_a?(Sketchup::Face) && e.back_material
      end
    end
    model.entities.each { |e| used[e.material] = true if e.respond_to?(:material) && e.material }
    gone = []
    model.start_operation('WR close-up material cleanup', true)
    extra.each do |m|
      next if used[m]
      nm = m.name
      gone << "material #{nm}" if (model.materials.remove(m) rescue false)
    end
    model.commit_operation
    gone
  rescue StandardError => e
    ["material cleanup failed: #{e.class}: #{e.message}"]
  end

  # run(opts) — no dialogs; returns a summary hash (the bridge returns it as
  # JSON). opts: shots ('pilot' | 'all' | 'CU-03,CU-06:seated'), dry (bool),
  # out (folder), over (bool), check (bool, anchor-check pass), recover
  # (bool), spec (path).
  def self.run(opts = {})
    load_shading
    model = Sketchup.active_model
    spec = load_spec(opts['spec'])
    rig = spec['rig'] || {}
    poses = {}
    spec['shots'].each { |id, s| poses[id] = s['pose'] if s['pose'] }
    jobs, miss = pick_shots(poses, opts['shots'] || 'pilot')
    dry = opts.key?('dry') ? !!opts['dry'] : true
    out = (opts['out'] || rig_value(rig, 'out_dir', DEF_OUT)).to_s.tr('\\', '/')
    run = { :model => model, :spec => spec, :dry => dry, :out => out,
            :over => !!opts['over'], :check => opts.key?('check') ? !!opts['check'] : true,
            :root => (opts['component_root'] || rig_value(rig, 'component_root', 'Z:/Sketchup/NewMasterComponentList')).to_s,
            :roots => ([opts['component_root'] || rig_value(rig, 'component_root', 'Z:/Sketchup/NewMasterComponentList')] +
                       Array(rig_value(rig, 'component_fallback_roots', []))).map(&:to_s).uniq,
            :index => nil, :written => [], :loaded => [], :stuck => [],
            :style_used => nil, :shading_lines => [] }
    FileUtils.mkdir_p(out)

    fp0 = fingerprint(model)
    defs0 = model.definitions.map(&:persistent_id)
    mats0 = model.materials.map(&:name)
    run[:mats0] = mats0
    closed = close_contexts(model)
    run[:infile] = {}
    run[:infile_index] = {}
    preload_files(run, poses, jobs)
    view = model.active_view
    cam0 = save_camera(view)
    results = []
    started = Time.now
    begin
      jobs.each do |sid, var|
        results << do_shot(run, sid, var)
      end
    ensure
      restore_camera(view, cam0)
      Sketchup.status_text = ''
    end
    stuck = run[:stuck]
    style_used = run[:style_used]
    shading_lines = run[:shading_lines]

    removed = cleanup_defs(model, defs0)
    removed += cleanup_materials(model, mats0)
    recovered = nil
    if !dry && !run[:written].empty? && rig_value(rig, 'recover', true) && opts['recover'] != false
      recovered = WR_Shading.recover(out)
      cdir = File.join(out, '_anchorcheck')
      WR_Shading.recover(cdir) if File.directory?(cdir)
    end
    fp1 = fingerprint(model)
    diffs = fp_diff(fp0, fp1)

    meta = { 'model' => model.title.to_s, 'model_path' => model.path.to_s, 'sketchup' => Sketchup.version.to_s,
             'rig_version' => RIG_VERSION, 'spec' => spec['_path'], 'spec_source' => spec['source'],
             'generated_at' => Time.now.utc.strftime('%Y-%m-%dT%H:%M:%SZ'),
             'style' => (dry ? nil : style_used), 'dark' => rig_value(rig, 'dark', 45),
             'ao' => false }
    rows_written = dry ? nil : write_json(out, results, meta)
    diag = write_diagnostics(out, run, results, meta, fp0, diffs, removed, closed, stuck,
                             (dry ? [] : shading_lines), miss, recovered, Time.now - started)
    print_summary(run, results, diffs, removed, diag, miss)

    { 'mode' => dry ? 'dry' : 'render', 'model' => model.title.to_s, 'out' => out,
      'shots' => results.map do |r|
        { 'shot' => r['shot'], 'variant' => r['variant'], 'status' => r['status'], 'file' => r['file'],
          'reason' => r['reason'], 'missing' => r['missing'], 'anchors' => r['anchors'],
          'anchors_missing' => r['anchors_missing'], 'warnings' => r['warnings'], 'generated' => r['generated'],
          'parts' => r['parts'], 'subject_corners_outside' => r['subject_corners_outside'] }
      end,
      'unmatched_tokens' => miss, 'restored' => diffs.empty?, 'restore_diffs' => diffs,
      'definitions_removed' => removed, 'contexts_closed' => closed, 'shading_stuck' => stuck,
      'json_rows' => rows_written, 'diagnostics' => diag }
  end

  # _closeups.json: one row per image, merged with what the folder already
  # holds (keyed by file), so two passes in two models fill one file.
  def self.write_json(out, results, meta)
    path = File.join(out, '_closeups.json')
    rows = {}
    if File.exist?(path)
      begin
        old = JSON.parse(File.read(path, :encoding => 'UTF-8'))
        Array(old['images']).each { |r| rows[r['file']] = r }
      rescue StandardError
        File.rename(path, path + ".unreadable-#{Time.now.strftime('%Y%m%d%H%M%S')}") rescue nil
      end
    end
    results.each do |r|
      next unless r['status'].to_s.start_with?('rendered')
      rows[r['file']] = {
        'file' => r['file'], 'shot' => r['shot'], 'variant' => r['variant'], 'title' => r['title'],
        'w' => r['w'], 'h' => r['h'], 'in_per_px' => r['in_per_px'], 'camera' => r['camera'],
        'section' => r['section'], 'explode' => r['explode'], 'anchors' => r['anchors'],
        'anchors_meta' => r['anchors_meta'], 'anchors_missing' => r['anchors_missing'],
        'missing' => r['missing'], 'warnings' => r['warnings'], 'anchor_check' => r['anchor_check'],
        'generated' => r['generated'] || [], 'parts' => r['parts'], 'moves' => r['moves'],
        'subject_corners_outside' => r['subject_corners_outside'],
        'model' => meta['model'], 'model_path' => meta['model_path'], 'sketchup' => meta['sketchup'],
        'style' => meta['style'], 'dark' => meta['dark'], 'ao' => meta['ao'],
        'rig_version' => meta['rig_version'], 'generated_at' => meta['generated_at']
      }
    end
    doc = { 'version' => 1, 'note' => 'Written by scripts/am-closeup-export.rb. Anchors are image pixels, ' \
                                       'origin top-left, y down. Labels are drawn by the app.',
            'images' => rows.values.sort_by { |r| [r['shot'].to_s, r['variant'].to_s] } }
    File.open(path, 'w:UTF-8') { |f| f.write(JSON.pretty_generate(doc)) }
    rows.length
  rescue StandardError => e
    puts "  (could not write _closeups.json: #{e.class}: #{e.message})"
    nil
  end

  def self.write_diagnostics(out, run, results, meta, fp0, diffs, removed, closed, stuck, shading, miss, recovered, secs)
    path = File.join(out, '_diagnostics.txt')
    File.open(path, 'a:UTF-8') do |f|
      f.puts '=' * 78
      f.puts "ASSEMBLY CLOSE-UPS — #{run[:dry] ? 'DRY RUN' : 'RENDER'}   #{meta['generated_at']}"
      f.puts "model        #{meta['model']}   (#{meta['model_path']})"
      f.puts "sketchup     #{meta['sketchup']}   rig #{meta['rig_version']}"
      f.puts "spec         #{meta['spec']}"
      f.puts "spec source  #{meta['spec_source'].to_json}"
      f.puts "out          #{run[:out]}   overwrite #{run[:over]}   anchor check #{run[:check]}"
      f.puts "components   #{run[:roots].join('  then  ')}"
      f.puts "contexts closed on entry: #{closed}"
      f.puts format('elapsed      %.1f s', secs.to_f)
      f.puts "unmatched shot tokens: #{miss.join(', ')}" unless miss.empty?
      unless shading.empty?
        f.puts ''
        f.puts 'SHADING CONTRACT AS RENDERED (diff against the Iso30 DoorCombos block)'
        shading.each { |l| f.puts "  #{l}" }
        f.puts "  ao                   #{meta['ao']}"
      end
      unless stuck.empty?
        f.puts '  KEYS THAT WOULD NOT TAKE:'
        stuck.each { |s| f.puts "    #{s}" }
      end
      results.each do |r|
        f.puts ''
        f.puts "#{r['shot']} #{r['variant']} — #{r['status'].upcase}   #{r['file']}"
        f.puts "  #{r['title']}"
        f.puts "  reason: #{r['reason']}" if r['reason']
        r['missing'].each { |m| f.puts "  MODEL GAP  #{m}" }
        r['parts'].each do |pt|
          f.puts "  part #{pt['role']}#{pt['optional'] ? ' (optional)' : ''}: #{pt['how'] || 'NOT FOUND'}"
          Array(pt['pieces']).each do |pc|
            sz = pc['size_in'] ? pc['size_in'].map { |v| format('%.2f', v) }.join(' x ') : '?'
            f.puts "      piece  #{pc['name']}   #{sz} in"
          end
          f.puts "      + #{pt['loose_entities']} loose edge/face entities" if pt['loose_entities'].to_i > 0
        end
        if r['camera']
          c = r['camera']
          f.puts "  camera #{c['persp'] ? 'PERSPECTIVE fov ' + c['fov'].to_s : 'parallel, view height ' + c['height'].to_s + ' in'}" \
                 "  azimuth #{c['azimuth']} elev #{c['elevation']} (#{c['how']})"
          f.puts "         target #{c['target'].inspect}  eye #{c['eye'].inspect}"
          f.puts "  canvas #{r['w']} x #{r['h']}  #{r['in_per_px'] ? format('%.5f in/px', r['in_per_px']) : ''}"
        end
        f.puts "  subject #{r['subject_box_in'].inspect} in; #{r['subject_corners_outside']} of 8 box corners outside the frame" if r['subject_box_in']
        f.puts "  section #{r['section'].inspect}" if r['section']
        f.puts "  explode #{r['explode']}" unless r['explode'].nil?
        r['anchors'].each do |nm, xy|
          m = r['anchors_meta'][nm] || {}
          f.puts format('  anchor %-16s px %-18s world %s%s%s', nm, xy.inspect, m['world'].inspect,
                        m['in_frame'] ? '' : '  OUTSIDE THE FRAME', m['fallback'] ? '  (fallback)' : '')
        end
        r['anchors_missing'].each { |nm| f.puts "  anchor #{nm} DID NOT RESOLVE — no pixel written" }
        r['warnings'].each { |w| f.puts "  warning: #{w}" }
        f.puts "  anchor check: #{r['anchor_check']}" if r['anchor_check']
        Array(r['backtrace']).each { |b| f.puts "    at #{b}" }
      end
      f.puts ''
      f.puts "brightness recovery: #{recovered.inspect}" unless recovered.nil?
      f.puts "loaded definitions removed again after the aborts: #{removed.join(', ')}" unless removed.empty?
      f.puts 'RESTORE CHECK (fingerprint before vs after the run)'
      if diffs.empty?
        f.puts '  identical — entities, hidden flags, definitions, materials, tags, scenes, style,'
        f.puts '  rendering and shadow keys, section, camera, modified flag'
      else
        diffs.each { |d| f.puts "  *** #{d}" }
      end
    end
    path
  rescue StandardError => e
    puts "  (could not write _diagnostics.txt: #{e.class}: #{e.message})"
    nil
  end

  def self.print_summary(run, results, diffs, removed, diag, miss)
    puts ''
    puts "ASSEMBLY CLOSE-UPS #{run[:dry] ? '(DRY RUN — nothing rendered)' : ''}"
    results.each do |r|
      puts format('  %-6s %-10s %-24s %s', r['shot'], r['variant'], r['status'], r['reason'].to_s)
      r['missing'].each { |m| puts "           MODEL GAP #{m}" }
      puts "           anchors not resolved: #{r['anchors_missing'].join(', ')}" unless r['anchors_missing'].empty?
      r['warnings'].each { |w| puts "           warning: #{w}" }
    end
    puts "  shot tokens that matched nothing: #{miss.join(', ')}" unless miss.empty?
    puts "  definitions removed after abort: #{removed.length}" unless removed.empty?
    puts diffs.empty? ? '  model restored: fingerprint identical' : "  *** model NOT identical: #{diffs.join('; ')}"
    puts "  diagnostics: #{diag}"
  end

  # survey('duct box') — every definition whose name matches, with its size,
  # how many instances the model holds (nested included) and where the first
  # few sit. For turning a MODEL GAP into a working pose.
  def self.survey(pattern, limit = 40)
    model = Sketchup.active_model
    re = rx(pattern)
    idx, = instance_index(model, nil)
    by = Hash.new { |hh, k| hh[k] = [] }
    idx.each { |it| by[it[:ent].respond_to?(:definition) ? (it[:ent].definition rescue nil) : nil] << it }
    out = []
    model.definitions.each do |d|
      next if d.image?
      next unless name_hit?(re, d.name)
      b = d.bounds
      its = by[d]
      out << { 'definition' => d.name, 'size_in' => [b.width, b.height, b.depth].map { |v| v.to_f.round(2) },
               'instances' => its.length,
               'examples' => its.first(3).map do |it|
                 { 'origin' => arr(it[:tr].origin).map { |v| v.round(2) },
                   'path' => it[:path].join(' > ') }
               end }
      break if out.length >= limit
    end
    out.each do |r|
      puts format('  %-50s %-26s x%d', r['definition'], r['size_in'].inspect, r['instances'])
      r['examples'].each { |e| puts "      at #{e['origin'].inspect} in #{e['path'].empty? ? 'top level' : e['path']}" }
    end
    out
  end

