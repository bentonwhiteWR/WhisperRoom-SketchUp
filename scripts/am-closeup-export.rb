# @title Assembly close-ups — export (manual insets)...
# @cat Component art (web catalog)
# @icon art-angled
#
# Close-up insets for the assembly manual: a few named parts per picture,
# context ghosted or hidden, optional explode, optional section cut, a camera
# per shot, on a WIDE canvas, in the same style and lighting as the Iso30
# sprites. Exports transparent PNGs named <shot-id>_<variant>.png, plus
# _diagnostics.txt (human) and _closeups.json (machine), into
# Z:\Sketchup\BoothBuilderViews\AssemblyCloseups\ by default.
#
# NO TEXT IS BAKED INTO THE IMAGES. Callout labels are drawn by the app, so the
# rig exports the PIXEL POSITION of each named 3D point ("anchor") per image,
# and the app draws the leader lines in its own type. Rewording a callout never
# needs a re-export.
#
# ===========================================================================
# THE CONTRACT
#
#   * The model is RESTORED EXACTLY. Each shot runs inside its own
#     start_operation / abort_operation, so staging, explodes, ghosting, the
#     section plane and every hidden flag are undone. Camera, style, shading
#     and tag visibility are put back in an ensure. Definitions a shot loaded
#     from disk that survive the abort are removed again. A fingerprint of the
#     model is taken before and after the run and the diff is printed and
#     written — "restored" is a measured claim, not a hope.
#   * NOTHING IS SAVED. There is no save call in this file, and under the
#     bridge any save raises.
#   * A SHOT IS NEVER DRAWN HALF-EMPTY. A part that cannot be found is a MODEL
#     GAP: the shot is skipped and named, never rendered without it (the
#     save-scene-components.rb rule). Parts marked "optional" are the exception.
#
# WHERE THE SHOTS COME FROM
#
#   scripts/am-closeups.json, GENERATED by scripts/gen-am-closeups.py from the
#   scoper's shot-list.csv (titles, steps, priorities, prose) plus
#   scripts/am-closeups-poses.json (the machine pose for each shot that has
#   been posed). Edit the poses file and re-run the generator; never edit
#   am-closeups.json by hand.
#
# HOW A SHOT IS STAGED — stage, don't hunt
#
#   Every part named in the pose is placed as a FRESH instance inside one
#   staging group, and everything else at top level is hidden. A part comes
#   from, first that resolves:
#     def   a definition already in the open model, placed at its own origin
#     file  <component_root>\<file>.skp (NewMasterComponentList), loaded at its origin
#     find  an instance anywhere in the open model (nested too), copied at its
#           WORLD position — this is how Benton's posed models are reused
#   "split": n explodes the staged copy n levels so its children can be moved,
#   ghosted or hidden one by one. Exploding a STAGED copy never edits a shared
#   definition; that is the reason for staging at all.
#
# Order per shot: stage -> split -> moves -> section axis -> camera -> anchors
# -> hides -> ghosts -> section plane -> render -> anchor-check render -> abort.
# Anchors are resolved BEFORE ghosting, because ghosting flattens a part to raw
# faces and its named children stop existing.
#
# STYLE AND LIGHTING = the Iso30 contract (wr-shading.rb): "Style: Interior",
# Dark 45, Light 80, sun-for-shading off, shadows off, ground/sky/fog/
# watermark/AO off, transparent background, then fix-angled-alpha.py over the
# folder (the new graphics engine's 75% dark composite). There is NO ambient-
# occlusion pass: the last Iso30 run (DoorCombos/extra) saved ao="" in
# SketchUp's prefs, which that rig reads as off, so the sprites these sit
# beside were shot without it. All of it is set inside each shot's operation.
#
# ANCHORS are projected ANALYTICALLY from the camera (parallel: scale =
# image height / view height), not read off view.screen_coords, because the
# viewport's aspect is not the export's. The anchor-check pass renders a red
# dot at every anchor into _anchorcheck\<stem>.png with everything else hidden;
# scripts/am-closeup-check.py measures each dot against the JSON and fails any
# anchor more than 6 px out. That is the evidence the projection is right.
#
# RUN IT
#   Panel: WhisperRoom > Component art > Assembly close-ups.
#   Bridge (no dialogs):
#     python scripts/sketchup-bridge.py eval "load File.join(WhisperRoom::Tools::SCRIPTS_DIR, 'am-closeup-export.rb'); WR_AmCloseups.run('shots' => 'pilot', 'dry' => true)" --timeout 600 --write-root "Z:/Sketchup/BoothBuilderViews/AssemblyCloseups"
#   then the same with 'dry' => false. WR_AmCloseups.survey('duct box') lists
#   every definition matching a pattern, with sizes and where its instances sit,
#   for fixing a MODEL GAP.
#
#   load "C:/Users/bento/Documents/Claude/Sketchup/scripts/am-closeup-export.rb"

